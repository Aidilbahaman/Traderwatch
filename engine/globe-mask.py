#!/usr/bin/env python3
"""Build a real earth-globe asset for the TraderWatch landing page.

Produces two files consumed by index.html:

  globe-land.js   land/water mask at 0.5 degree resolution (360x180),
                  run-length encoded so it stays a reasonable payload.
  globe-cities.js visitor coordinates, one row per ping.

Why a generated mask instead of a bundled shapefile: the landing page is a
single static HTML file with no build step, so the landmask has to be inlined
or fetched as a small JS file. 0.5 degree gives recognisable coastlines at the
336px globe size, which 5 degree (the previous 72x36 grid) cannot.

Source data: Natural Earth 110m land polygons, fetched once and cached under
state/. Re-run is safe and idempotent.
"""
import json
import pathlib
import sys

OUT_DIR = pathlib.Path("/home/ubuntu/web/Traderwatch-repo")
CACHE = pathlib.Path("/home/ubuntu/web/Traderwatch-repo/state/ne110m_land.json")

# Bump when the grid or encoding changes.
MASK_VERSION = 2
RES = 0.5          # degrees per cell
W = int(360 / RES)  # 720 columns
H = int(180 / RES)  # 360 rows


def load_land_polygons():
    """Return a list of polygons (each a list of [lon, lat]) for world land."""
    if CACHE.exists():
        return json.loads(CACHE.read_text())

    import urllib.request
    url = ("https://raw.githubusercontent.com/nvkelso/natural-earth-vector/"
           "master/geojson/ne_110m_land.geojson")
    req = urllib.request.Request(url, headers={"User-Agent": "TraderWatch-globe/1.0"})
    with urllib.request.urlopen(req, timeout=120) as r:
        gj = json.loads(r.read().decode())

    polys = []
    for feat in gj["features"]:
        geom = feat["geometry"]
        coords = geom["coordinates"]
        if geom["type"] == "Polygon":
            polys.append(coords[0])
        elif geom["type"] == "MultiPolygon":
            for poly in coords:
                polys.append(poly[0])

    CACHE.parent.mkdir(parents=True, exist_ok=True)
    CACHE.write_text(json.dumps(polys))
    return polys


def point_in_poly(lon, lat, poly):
    """Ray casting. poly is [[lon,lat], ...]."""
    inside = False
    n = len(poly)
    j = n - 1
    for i in range(n):
        xi, yi = poly[i][0], poly[i][1]
        xj, yj = poly[j][0], poly[j][1]
        if (yi > lat) != (yj > lat):
            xint = (xj - xi) * (lat - yi) / (yj - yi + 1e-12) + xi
            if lon < xint:
                inside = not inside
        j = i
    return inside


def build_mask(polys):
    """720x360 grid of 0/1. Row 0 is +90 lat, col 0 is -180 lon."""
    # Pre-compute each polygon's bbox so the per-cell test stays cheap.
    boxes = []
    for p in polys:
        lons = [pt[0] for pt in p]
        lats = [pt[1] for pt in p]
        boxes.append((min(lons), min(lats), max(lons), max(lats), p))

    grid = []
    for r in range(H):
        lat = 90 - (r + 0.5) * RES
        row = []
        for c in range(W):
            lon = -180 + (c + 0.5) * RES
            hit = 0
            for (x0, y0, x1, y1, poly) in boxes:
                if lon < x0 or lon > x1 or lat < y0 or lat > y1:
                    continue
                if point_in_poly(lon, lat, poly):
                    hit = 1
                    break
            row.append(hit)
        grid.append(row)
    return grid


def rle_rows(grid):
    """Run-length encode each row into [start, length] pairs of land runs."""
    out = []
    for row in grid:
        runs = []
        c = 0
        while c < len(row):
            if row[c]:
                start = c
                while c < len(row) and row[c]:
                    c += 1
                runs.append([start, c - start])
            else:
                c += 1
        out.append(runs)
    return out


def main():
    polys = load_land_polygons()
    print("poligon daratan:", len(polys))

    grid = build_mask(polys)
    land = sum(sum(r) for r in grid)
    print("sel daratan: %d / %d (%.1f%%)" % (land, W * H, 100.0 * land / (W * H)))

    runs = rle_rows(grid)
    payload = {"v": MASK_VERSION, "res": RES, "w": W, "h": H, "rows": runs}
    body = json.dumps(payload, separators=(",", ":"))
    js = ("/* TraderWatch earth landmask, %s deg, %dx%d, RLE. "
          "Generated by engine/globe-mask.py - do not hand edit. */\n"
          "window.TW_LAND=%s;\n" % (RES, W, H, body))
    (OUT_DIR / "globe-land.js").write_text(js)
    print("globe-land.js: %.1f KB" % (len(js) / 1024.0))
    return 0


if __name__ == "__main__":
    sys.exit(main())
