def log(msg):
    line = f"[{datetime.now(TZ_MY).strftime('%Y-%m-%d %H:%M:%S MY')}] {msg}"
    print(line, flush=True)
    try:
        with LOG.open("a") as f:
            f.write(line + "\n")
    except Exception:
        pass


def get_token():
    env = dict(l.split("=", 1) for l in
               (SECRETS / "telegram.env").read_text().splitlines()
               if "=" in l and not l.startswith("#"))
    return (env.get("TELEGRAM_SIGNALS_BOT_TOKEN")
            or env.get("TELEGRAM_BOT_TOKEN", "")).strip()


def send_photo(caption, poster):
    """Multipart sendPhoto with the chosen brand poster."""
    token = get_token()
    if not token:
        raise RuntimeError("no Telegram token in ~/.secrets/telegram.env")
    if not poster.exists():
        raise RuntimeError(f"poster missing: {poster}")
    boundary = "----TWChannelPromo"
    photo = poster.read_bytes()

    def part(name, value, filename=None, ctype=None):
        s = f'--{boundary}\r\nContent-Disposition: form-data; name="{name}"'
        if filename:
            s += f'; filename="{filename}"'
        s += "\r\n"
        if ctype:
            s += f"Content-Type: {ctype}\r\n"
        s += "\r\n"
        return s.encode() + (value if isinstance(value, bytes) else value.encode()) + b"\r\n"

    body = b"".join([
        part("chat_id", CHAT_ID),
        part("photo", photo, "poster.png", "image/png"),
        part("caption", caption),
        part("parse_mode", "HTML"),
    ]) + f"--{boundary}--\r\n".encode()
    req = urllib.request.Request(
        f"https://api.telegram.org/bot{token}/sendPhoto", data=body,
        headers={"Content-Type": f"multipart/form-data; boundary={boundary}"})
    try:
        with urllib.request.urlopen(req, timeout=90) as r:
            res = json.load(r)
    except urllib.error.HTTPError as e:
        res = json.load(e)
    if not res.get("ok"):
        raise RuntimeError(f"Telegram {res.get('error_code')}: {res.get('description')}")
    return (res.get("result") or {}).get("message_id")


def load_state():
    try:
        return json.loads(STATE.read_text())
    except Exception:
        return {}


def save_state(s):
    tmp = STATE.with_suffix(".tmp")
    tmp.write_text(json.dumps(s))
    os.replace(tmp, STATE)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--next", action="store_true",
                    help="post the NEXT slot's promo now and mark that slot done")
    args = ap.parse_args()

    if DISABLE_FILE.exists():
        log("disabled by kill switch; nothing sent")
        return 0

    state = load_state()
    if state.get("fails", 0) >= MAX_FAILS:
        log(f"HALTED after {MAX_FAILS} consecutive failures; human reset required")
        return 1

    slot = int(time.time() // SLOT_SECONDS)
    if args.next:
        slot = max(slot, state.get("last_slot", slot)) + 1
    idx = slot % len(PROMOS)
    text = PROMOS[idx]
    if len(text) > 1024:
        log(f"caption too long ({len(text)}); skipping")
        return 1

    now = time.time()
    if not args.force and not args.next:
        if state.get("last_slot") == slot:
            log(f"slot {slot} already posted; skipping")
            return 0
        if now - state.get("last_sent", 0) < MIN_INTERVAL_MIN * 60:
            log("rate limited; skipping")
            return 0

    poster = POSTERS[idx % len(POSTERS)]
    if args.dry_run:
        log(f"DRY RUN — slot={slot} idx={idx} poster={poster.name}\n{text}")
        return 0

    try:
        mid = send_photo(text, poster)
    except Exception as e:
        fails = state.get("fails", 0) + 1
        state.update(fails=fails, last_error=str(e)[:200])
        save_state(state)
        log(f"SEND FAILED ({fails}/{MAX_FAILS}): {e}")
        return 1

    state.update(fails=0, last_sent=now, last_slot=slot, last_message_id=mid,
                 last_kind="photo", last_idx=idx, last_poster=poster.name)
    state.pop("last_error", None)
    save_state(state)
    log(f"sent message_id={mid} kind=photo idx={idx} poster={poster.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
